# 변수와 타입
age = 30 # 변수 만들기 (let, const 없음)
str(30) # 숫자 → 문자
int("30") # 문자 → 정수
float("3.5") # 문자 → 소수
type(30) # 타입 확인

# 변수와 타입(응용)
int("3") + 4 # 7 → 문자로 받은 값을 계산 할 때
"개수: " + str(3) # '개수: 3' → 숫자를 문장에 붙일 때
a = 3
b = 6
a, b = b, a # a = 6 / b = 3 → 두 값을 맞바꿀 때
bool(""), bool([]) # False → 비어 있는지 검사할 때

