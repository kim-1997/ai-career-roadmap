# 반복·필터·정렬
for n in [1, 2, 3]: # 1 / 2 / 3 → 하나씩 반복
    print(n)
for i in range(3): # 0 / 1 / 2 → 횟수만큼 반복 (끝 번호는 제외)
    print(i)
[n * 2 for n in [1, 2, 3]] # [2, 4, 6] → 값 변환 (JS의 map)
[n for n in [1, 2, 3] if n > 1] # [2, 3] → 값 거르기 (JS의 filter)
users = [{"name": "민수", "age": 30}, {"name": "지영", "age": 25}]
sorted(users, key=lambda user: user["age"]) # [{'name': '지영', 'age': 25}, {'name': '민수', 'age': 30}] → 기준을 정해 정렬

# 반복·필터·정렬(응용)
for i, v in enumerate(["a", "b"]): # 0 a / 1 b → 번호와 값을 함께 반복할 때
    print(i, v)
list(zip(["a", "b"], [1, 2])) # [('a', 1), ('b', 2)] → 두 리스트를 나란히 묶을 때
sorted(["bb", "a"], key=len) # ['a', 'bb'] → 길이순으로 정렬할 때
any(n > 2 for n in [1, 2, 3]) # True → 하나라도 맞는지 확인
all(n > 0 for n in [1, 2, 3]) # True → 전부 맞는지 확인
