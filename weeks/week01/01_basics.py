# 문자열
name = "Python"
f"{name}님" # "Python님" → 문장에 값 넣기
len("Python") # 6 → 길이 구하기
"Python"[0] # 'P' → 첫글자 구하기
"Python"[-1] # 'n' → 마지막 글자 구하기
"Python"[1:4] # 'yth' → 문자열 자르기(끝 번호는 제외)
"  Python  ".strip() # 'Python' → 앞뒤 공백 제거
"a.b".split(".") # ['a', 'b'] → 잘라서 리스트로 만들기
"-".join(["a", "b"]) # 'a-b' → 리스트 합치기
"사과".replace("사", "배") # '배과' → 글자 바꾸기
"Py" in "Python" # True → 문자열 포함 여부(대소문자 구분)

# 문자열(응용)
"Python"[::-1] # 'nohtyP' → 문자열 뒤집을 때
"HELLO".lower() # 'hello' → 모든 영문을 소문자로 변경(대소문자 무시하고 비교할 때, upper()은 대문자)
"hello.py".endswith(".py") # True → 문자열이 특정 문자로 끝나는지 확인 ex) 업로드 파일 확장자 검사 할 때
"3".isdigit() # True → 모든 글자가 숫자인지 확인
"banana".count("a") # 3 → 문자열 안에 특정 문자가 몇 번 등장하는지 확인
f"{1000:,}" # 1,000 → 가격 표시할 때
list("abc") # ['a', 'b', 'c'] → 글자를 하나씩 리스트로 나눌 때

