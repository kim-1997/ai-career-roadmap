# 딕셔너리
u = {"name": "민수"} # 딕셔너리 만들기 (키에 따옴표, JS의 객체)
u["name"] # '민수' → 값 꺼내기 (u.name은 안 됨)
u.get("x") # None → 키가 없어도 에러 없이 꺼낼 때
u["age"] = 30 # {'name': '민수', 'age': 30} → 추가·수정
"name" in u # True → 키가 있는지 확인
for k, v in u.items(): # name 민수 / age 30 → 키와 값을 함께 반복할 때
    print(k, v)

# 딕셔너리(응용)
u.get("x", 0) # 0 → 키가 없을 때 기본값 정하기
c = {}
for w in ["a", "b", "a"]:
    c[w] = c.get(w, 0) + 1 # {'a': 2, 'b': 1} → 개수 셀 때 (코테 단골)
u.pop("age") # 30 → 키 삭제 (삭제한 값을 돌려줌)
list(u.keys()) # ['name'] → 키 목록 구하기
list(u.values()) # ['민수'] → 값 목록 구하기
dict(zip(["a", "b"], [1, 2])) # {'a': 1, 'b': 2} → 리스트 2개를 묶어 딕셔너리로 만들 때

# ----------------------------------------------------------- #

# 집합
set([1, 1, 2]) # {1, 2} → 중복 제거 (순서가 없어서 번호로 꺼낼 수 없음)
2 in {1, 2} # True → 포함 여부 (리스트보다 빠름)
set() # set() → 빈 집합 만들기 ({}는 딕셔너리)

# 집합(응용)
len(set([1, 1, 2])) # 2 → 종류 개수 셀 때
{1, 2} & {2, 3} # {2} → 공통 값 찾을 때
{1, 2} | {2, 3} # {1, 2, 3} → 전부 합칠 때
{1, 2} - {2, 3} # {1} → 빠진 값 찾을 때

