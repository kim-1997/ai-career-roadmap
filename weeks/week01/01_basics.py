# 숫자
7 / 2	# 3.5 → 나누기 항상 소수
7 // 2	# 3	→ 몫
7 % 2	# 1	→ 나머지
sum([1, 2, 3])	# 6	→ 합계
max([1, 2, 3])	# 3	→ 최댓값, min은 최솟값

# 숫자(응용)
4 % 2 == 0 # True → 짝수를 판별할 때
25 // 10 + (1 if 25 % 10 else 0) # 3 → 글 25개를 10개씩 나눌 때 전체 쪽수
(3 - 1) * 10 # 20 → 3쪽을 볼 때 건너뛸 글의 수
round(3.14159, 2) # 3.14 → 소수 자리 맞추기
sum([1, 2]) / len([1, 2]) # 1.5 → sum = 리스트의 합 / len = 리스트의 길이 평균을 구할 때

