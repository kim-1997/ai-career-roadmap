# 튜플
t = (1, 2) # 튜플 만들기 (수정할 수 없는 리스트)
t[0] # 1 → 값 꺼내기
x, y = t # x = 1 / y = 2 → 풀어서 받기 (JS의 구조 분해)

# 튜플(응용)
def get_pair():
    return 1, 2 # (1, 2) → 함수에서 값 2개를 돌려줄 때

get_pair() # (1, 2) → 함수 실행 결과
