# 리스트
nums = [3, 1, 2] # 리스트 만들기
nums[0] # 3 → 첫 번째 값 꺼내기
nums[-1] # 2 → 마지막 값 꺼내기
nums.append(4) # 값은 None → 끝에 추가 (nums는 [3, 1, 2, 4], JS의 push)
nums.pop() # 4 → 끝에서 꺼내기
len(nums) # 3(pop() 을 했기 때문에 nums = [3, 1, 2]) → 개수 구하기
3 in nums # True → 포함 여부
sorted(nums) # [1, 2, 3] → 정렬한 새 리스트 만들기 (원본은 그대로)

# 리스트(응용)
sorted(nums, reverse=True) # [3, 2, 1] → 내림차순으로 정렬할 때
nums.sort() # None → 원본을 직접 정렬할 때 (반환값 없음)
nums.remove(1) # None → 값으로 지울 때 (nums는 [2, 3])
[1, 2] + [3] # [1, 2, 3] → 리스트 합칠 때
[0] * 3 # [0, 0, 0] → 같은 값으로 채울 때
nums.copy() # [2, 3] → 복사할 때 (b = a는 복사가 아니라 같은 리스트를 가리킴)

